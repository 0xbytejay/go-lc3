type spectrumReference struct {
	DT          int    `json:"dt"`
	SR          int    `json:"sr"`
	Pattern     int    `json:"pattern"`
	Frame       int    `json:"frame"`
	NBytes      int    `json:"nbytes"`
	Gain        int    `json:"gain"`
	NQ          int    `json:"nq"`
	LSB         int    `json:"lsb"`
	Offset      uint32 `json:"offset"`
	Spare       int    `json:"spare"`
	Status      int    `json:"status"`
	DecodedHash uint32 `json:"decodedHash"`
	Data        string `json:"data"`
}

func spectrumFloatHash(x []float32) uint32 {
	h := uint32(2166136261)
	for _, v := range x {
		u := math.Float32bits(v)
		for j := 0; j < 4; j++ {
			h = (h ^ uint32(byte(u>>(8*j)))) * 16777619
		}
	}
	return h
}

// These oracle vectors were generated by tools/reference_spectrum.c against
// liblc3 48bbd3eacd36e99a57317a0a4867002e0b09e183, scalar float32, no FMA.
func TestSpectrumReference(t *testing.T) {
	raw, err := os.ReadFile("testdata/spectrum_reference.json")
	if err != nil {
		t.Fatal(err)
	}
	var vectors []spectrumReference
	if err = json.Unmarshal(raw, &vectors); err != nil {
		t.Fatal(err)
	}
	if len(vectors) != 312 {
		t.Fatalf("unexpected oracle case count %d", len(vectors))
	}
	var state lc3_spec_analysis_t
	for _, v := range vectors {
		if v.Frame == 0 {
			state = lc3_spec_analysis_t{}
		}
		t.Run(fmt.Sprintf("dt%d_sr%d_pattern%d_frame%d", v.DT, v.SR, v.Pattern, v.Frame), func(t *testing.T) {
			ne := lc3_ne(v.DT, v.SR)
			x := make([]float32, ne)
			rng := uint32(0x51a2f339) + uint32(v.DT*1000+v.SR*100+v.Pattern*10+v.Frame)
			for i := range x {
				rng = rng*1664525 + 1013904223
				x[i] = float32(float32(int(rng>>16)-32768) * 0.03125)
				if v.Pattern == 0 || ((i+v.Pattern)%13 < 7 && v.Pattern == 1) {
					x[i] = 0
				}
				if v.Pattern == 2 {
					x[i] = float32(x[i] * 0.0001)
				}
				if v.Pattern == 3 {
					x[i] = float32(x[i] * 128)
				}
			}
			var side lc3_spec_side_t
			var tns lc3_tns_data_t
			lc3_spec_analyze(v.DT, v.SR, v.NBytes, v.Frame%2 != 0, &tns, &state, x, &side)
			if side.g_idx != v.Gain || side.nq != v.NQ || spec_bool(side.lsb_mode) != v.LSB || math.Float32bits(state.nbits_off) != v.Offset || state.nbits_spare != v.Spare {
				t.Errorf("analysis got side=%+v state=%+v; want gain%d nq%d lsb%d offset%08x spare%d", side, state, v.Gain, v.NQ, v.LSB, v.Offset, v.Spare)
			}
			out := make([]byte, v.NBytes)
			var bits lc3_bits_t
			lc3_setup_bits(&bits, lc3_BITS_MODE_WRITE, out, len(out))
			lc3_spec_put_side(&bits, v.DT, v.SR, &side)
			lc3_spec_encode(&bits, v.DT, v.SR, v.SR, v.NBytes, &side, x)
			lc3_flush_bits(&bits)
			want, err := hex.DecodeString(v.Data)
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(out, want) {
				i := 0
				for i < len(out) && out[i] == want[i] {
					i++
				}
				t.Errorf("encoded differs first byte%d got%02x want%02x", i, out[i], want[i])
			}
			// Decode the C-produced bytes independently of the Go encoder comparison.
			var decodedSide lc3_spec_side_t
			dec := make([]float32, ne)
			lc3_setup_bits(&bits, lc3_BITS_MODE_READ, want, len(want))
			status := lc3_spec_get_side(&bits, v.DT, v.SR, &decodedSide)
			if status == 0 {
				status = lc3_spec_decode(&bits, v.DT, v.SR, v.SR, v.NBytes, &decodedSide, dec)
			}
			if status == 0 {
				status = lc3_check_bits(&bits)
			}
			if status != v.Status {
				t.Errorf("decode status got%d want%d", status, v.Status)
			}
			if h := spectrumFloatHash(dec); h != v.DecodedHash {
				t.Errorf("decoded float hash got%08x want%08x", h, v.DecodedHash)
			}
		})
	}
}
